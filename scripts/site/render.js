/**
 * Renders the static part of the site: the article pages and their index,
 * sitemap.xml, robots.txt, the web manifest, 404.html, and the stylesheet
 * and fonts the static pages use. Returns { fileName → contents }; the Vite
 * plugin (./vitePlugin.js) writes them into the build and serves them in dev.
 */
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { SITE, absoluteUrl } from '../../site.config.js';
import { ARTICLES, articleSource } from './articles/index.js';
import { DATA_SOURCES, loadSiteData } from './data.js';
import { historyOf, latest } from './dates.js';
import { AUTHOR_LD, breadcrumbs, esc, longDate, renderPage } from './html.js';
import { createKit } from './kit.js';

const fromRoot = (path) => fileURLToPath(new URL(`../../${path}`, import.meta.url));

export const FONTS = ['big_noodle_titling.ttf', 'big_noodle_titling_oblique.ttf', 'config-regular-webfont.woff2'];

/** Visible words in an HTML fragment (for reading time). */
export const wordCount = (html) =>
  html
    .replace(/<(script|style|svg)[\s\S]*?<\/\1>/g, ' ')
    .replace(/<[^>]+>/g, ' ')
    .replace(/&[a-z#0-9]+;/gi, ' ')
    .split(/\s+/)
    .filter((w) => /[a-z0-9]/i.test(w)).length;

const stripTags = (html) => html.replace(/<[^>]+>/g, '').replace(/\s+/g, ' ').trim();

/** "<title>": the article title, plus the site name when it still fits in a search result. */
const pageTitle = (title) => (title.length + SITE.name.length + 3 <= 70 ? `${title} | ${SITE.name}` : title);

function stylesheet() {
  const tokens = readFileSync(fromRoot('src/styles/tokens.css'), 'utf8');
  const own = readFileSync(fromRoot('scripts/site/site.css'), 'utf8');
  const faces = `@font-face { font-family: 'Big Noodle Titling'; src: url('fonts/big_noodle_titling.ttf') format('truetype'); font-weight: 400; font-style: normal; font-display: swap; }
@font-face { font-family: 'Big Noodle Titling'; src: url('fonts/big_noodle_titling_oblique.ttf') format('truetype'); font-weight: 400; font-style: italic; font-display: swap; }
@font-face { font-family: 'Config'; src: url('fonts/config-regular-webfont.woff2') format('woff2'); font-weight: 400; font-style: normal; font-display: swap; }
`;
  return `/* Generated by scripts/site/render.js from src/styles/tokens.css and scripts/site/site.css. */\n${faces}\n${tokens}\n${own}`;
}

function renderArticle(article, d, dates, bySlug) {
  const root = '../../';
  const path = `articles/${article.slug}/`;
  const kit = createKit(d, root);
  const description = article.description(d);
  const body = article.body(d, kit);
  const words = wordCount(body);
  const crumbs = breadcrumbs(root, [
    { name: 'Articles', path: 'articles/' },
    { name: article.title, path },
  ]);
  const related = article.related.map((slug) => bySlug.get(slug));
  const keywords = typeof article.keywords === 'function' ? article.keywords(d) : article.keywords;

  const structuredData = [
    {
      '@context': 'https://schema.org',
      '@type': 'Article',
      headline: article.title,
      description,
      keywords: keywords.join(', '),
      articleSection: article.section,
      wordCount: words,
      inLanguage: SITE.language,
      datePublished: dates.published,
      dateModified: dates.modified,
      author: AUTHOR_LD,
      publisher: AUTHOR_LD,
      image: { '@type': 'ImageObject', url: absoluteUrl(SITE.ogImage.path), width: SITE.ogImage.width, height: SITE.ogImage.height },
      mainEntityOfPage: { '@type': 'WebPage', '@id': absoluteUrl(path) },
      isPartOf: { '@type': 'WebSite', name: SITE.name, url: SITE.url },
      about: { '@type': 'VideoGame', name: 'Overwatch' },
    },
    crumbs.data,
  ];
  if (article.faq) {
    structuredData.push({
      '@context': 'https://schema.org',
      '@type': 'FAQPage',
      mainEntity: article.faq(d, kit).map(({ q, a }) => ({
        '@type': 'Question',
        name: q,
        acceptedAnswer: { '@type': 'Answer', text: stripTags(a) },
      })),
    });
  }

  const main = `      ${crumbs.html}
      <article class="article">
        <header class="article-head">
          <p class="eyebrow">${esc(article.section)}</p>
          <h1 class="display slanted">${esc(article.title)}</h1>
          <p class="meta">Updated <time datetime="${dates.modified}">${longDate(dates.modified)}</time> · ${esc(d.season.name)} data · ${Math.max(1, Math.round(words / 230))} min read</p>
          <a class="button" href="${root}">Open the interactive chart</a>
        </header>
        <div class="prose">
${body}
        </div>
        <section class="related" aria-labelledby="related-title">
          <h2 id="related-title" class="display">Related articles</h2>
          <ul>
${related.map((r) => `            <li><a class="card panel" href="${kit.href(r.slug)}"><strong>${esc(r.title)}</strong><span>${esc(r.description(d))}</span></a></li>`).join('\n')}
          </ul>
        </section>
      </article>`;

  return {
    words,
    html: renderPage({
      path,
      root,
      title: pageTitle(article.title),
      description,
      body: main,
      ogType: 'article',
      structuredData,
      article: { published: dates.published, modified: dates.modified, section: article.section },
    }),
  };
}

function renderIndex(d, datesBySlug) {
  const root = '../';
  const path = 'articles/';
  const kit = createKit(d, root);
  const crumbs = breadcrumbs(root, [{ name: 'Articles', path }]);
  const title = 'Overwatch Rank Distribution Articles and Guides';
  const description = `Guides to the Overwatch rank distribution: rank percentages, percentiles, SR by rank, the average rank, and how the ${d.season.name} estimate is made.`;
  const main = `      ${crumbs.html}
      <div class="article">
        <header class="article-head">
          <p class="eyebrow">Articles</p>
          <h1 class="display slanted">Overwatch rank distribution guides</h1>
          <p class="lede">Plain-language guides to how competitive Overwatch players are spread across the ranks: what share of players is in each tier, which rank is the top 10% or top 1%, the SR every rank starts at, and how the estimate is made. Every number is computed from the same fitted curve as the <a href="${root}">interactive rank distribution chart</a>.</p>
          <a class="button" href="${root}">Open the interactive chart</a>
        </header>
        ${kit.estimateNote()}
        <ul class="article-list">
${ARTICLES.map(
  (a) => `          <li><a class="card panel" href="${kit.href(a.slug)}"><span class="eyebrow">${esc(a.section)}</span><strong>${esc(a.title)}</strong><span>${esc(a.description(d))}</span><time datetime="${datesBySlug.get(a.slug).modified}">Updated ${longDate(datesBySlug.get(a.slug).modified)}</time></a></li>`,
).join('\n')}
        </ul>
      </div>`;
  const structuredData = [
    {
      '@context': 'https://schema.org',
      '@type': 'CollectionPage',
      name: title,
      description,
      url: absoluteUrl(path),
      inLanguage: SITE.language,
      isPartOf: { '@type': 'WebSite', name: SITE.name, url: SITE.url },
      mainEntity: {
        '@type': 'ItemList',
        itemListElement: ARTICLES.map((a, i) => ({
          '@type': 'ListItem',
          position: i + 1,
          url: absoluteUrl(`articles/${a.slug}/`),
          name: a.title,
        })),
      },
    },
    crumbs.data,
  ];
  return renderPage({ path, root, title, description, body: main, structuredData });
}

function renderNotFound() {
  // Served for any missing path, at any depth, so every link is absolute.
  const root = SITE.url;
  const main = `      <div class="article">
        <header class="article-head">
          <p class="eyebrow">Error 404</p>
          <h1 class="display slanted">Page not found</h1>
          <p class="lede">There is nothing at this address. The rank distribution chart and the articles are still where they were.</p>
          <a class="button" href="${root}">Open the interactive chart</a>
        </header>
        <div class="prose">
          <h2>Popular pages</h2>
          <ul>
${ARTICLES.slice(0, 6).map((a) => `            <li><a href="${root}articles/${a.slug}/">${esc(a.title)}</a></li>`).join('\n')}
            <li><a href="${root}articles/">All articles</a></li>
          </ul>
        </div>
      </div>`;
  return renderPage({ path: '404.html', root, title: `Page not found | ${SITE.name}`, description: SITE.description, body: main, index: false });
}

function sitemap(entries) {
  return `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${entries.map(({ path, lastmod }) => `  <url>\n    <loc>${absoluteUrl(path)}</loc>\n    <lastmod>${lastmod}</lastmod>\n  </url>`).join('\n')}
</urlset>
`;
}

const robots = () => `# ${SITE.name}
User-agent: *
Allow: /

Sitemap: ${absoluteUrl('sitemap.xml')}
`;

const manifest = () =>
  `${JSON.stringify(
    {
      name: SITE.name,
      short_name: SITE.shortName,
      description: SITE.description,
      lang: SITE.language,
      start_url: './',
      scope: './',
      display: 'standalone',
      background_color: SITE.backgroundColor,
      theme_color: SITE.themeColor,
      icons: [
        { src: 'icons/icon-192.png', sizes: '192x192', type: 'image/png', purpose: 'any' },
        { src: 'icons/icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'any' },
      ],
    },
    null,
    2,
  )}\n`;

/**
 * Everything static, keyed by output path.
 * @returns {{ files: Map<string, string | Buffer>, articles: { slug: string, title: string, words: number }[] }}
 */
export function renderSite() {
  const d = loadSiteData();
  const bySlug = new Map(ARTICLES.map((a) => [a.slug, a]));
  for (const a of ARTICLES) {
    for (const slug of a.related) if (!bySlug.has(slug)) throw new Error(`${a.slug}: unknown related article "${slug}"`);
  }

  const data = historyOf(DATA_SOURCES);
  const datesBySlug = new Map(
    ARTICLES.map((a) => {
      const own = historyOf([articleSource(a.slug), 'scripts/site/kit.js', 'scripts/site/html.js']);
      return [a.slug, { published: historyOf([articleSource(a.slug)]).first, modified: latest(own.last, data.last) }];
    }),
  );
  const app = historyOf(['index.html', 'src', 'site.config.js']);

  const files = new Map();
  const articles = [];
  for (const a of ARTICLES) {
    const { html, words } = renderArticle(a, d, datesBySlug.get(a.slug), bySlug);
    files.set(`articles/${a.slug}/index.html`, html);
    articles.push({ slug: a.slug, title: a.title, words });
  }
  files.set('articles/index.html', renderIndex(d, datesBySlug));
  files.set('404.html', renderNotFound());
  files.set('articles/assets/site.css', stylesheet());
  for (const font of FONTS) files.set(`articles/assets/fonts/${font}`, readFileSync(fromRoot(`assets/fonts/${font}`)));

  const newestArticle = latest(...[...datesBySlug.values()].map((x) => x.modified));
  files.set(
    'sitemap.xml',
    sitemap([
      { path: '', lastmod: latest(app.last, data.last) },
      { path: 'articles/', lastmod: newestArticle },
      ...ARTICLES.map((a) => ({ path: `articles/${a.slug}/`, lastmod: datesBySlug.get(a.slug).modified })),
    ]),
  );
  files.set('robots.txt', robots());
  files.set('site.webmanifest', manifest());

  return { files, articles };
}

/**
 * The generated parts of the home page's text summary (the block at the
 * end of index.html: a text version of the chart for screen readers and
 * for visitors without JavaScript). `table` lists every tier with the
 * figures the chart shows; `links` is the list of articles.
 */
export function homeSummary() {
  const d = loadSiteData();
  const rows = [...d.tiers]
    .reverse()
    .map(
      (t) =>
        `<tr><th scope="row">${esc(t.name)}</th><td>${t.range}</td><td>${d.pct(t.share)}</td><td>${d.pct(t.below)}</td></tr>`,
    )
    .join('\n          ');

  const table = `<table>
        <caption>Estimated share of players in each rank, ${esc(d.season.name)}</caption>
        <thead>
          <tr><th scope="col">Rank</th><th scope="col">SR range</th><th scope="col">Share of players</th><th scope="col">Better than, at its lowest division</th></tr>
        </thead>
        <tbody>
          ${rows}
        </tbody>
      </table>`;

  const links = ARTICLES.map((a) => `<li><a href="articles/${a.slug}/">${esc(a.title)}</a></li>`).join('\n          ');

  return { table, links };
}
